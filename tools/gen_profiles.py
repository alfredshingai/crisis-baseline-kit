"""Generate country profiles from the Africa source audit.

Analysis CRS: mainland Africa -> ESRI:102022 (Africa Albers Equal Area
Conic; countries spanning multiple UTM zones get undistorted areas);
small island states -> local UTM zone.

Population quality gates: +/-40% around UN World Population Prospects
2020 estimates (with a minimum absolute width), tolerant of WorldPop's
unconstrained-vs-adjusted variance.

Admin-2 count gates are intentionally omitted on first build; they are
pinned afterwards from actual builds ("as built" ranges).

Usage: python tools/gen_profiles.py   (writes profiles/*.yaml, skips existing)
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# UN WPP 2020 population estimates, millions
POP_2020_M = {
    "DZA": 43.9, "AGO": 32.9, "BEN": 12.1, "BWA": 2.4, "BFA": 21.0, "BDI": 11.9,
    "CMR": 26.6, "CPV": 0.56, "CAF": 4.9, "TCD": 16.4, "COM": 0.87, "COG": 5.5,
    "COD": 90.0, "CIV": 26.4, "DJI": 0.99, "EGY": 102.3, "GNQ": 1.4, "ERI": 3.5,
    "SWZ": 1.2, "ETH": 115.0, "GAB": 2.3, "GMB": 2.5, "GHA": 31.1, "GIN": 13.1,
    "GNB": 2.0, "KEN": 53.8, "LSO": 2.2, "LBR": 5.1, "LBY": 6.9, "MDG": 27.7,
    "MWI": 19.1, "MLI": 20.3, "MRT": 4.6, "MUS": 1.27, "MAR": 36.9, "MOZ": 31.3,
    "NAM": 2.5, "NER": 24.2, "NGA": 206.1, "RWA": 13.0, "STP": 0.22, "SEN": 16.7,
    "SYC": 0.10, "SLE": 8.0, "SOM": 15.9, "ZAF": 59.3, "SSD": 11.2, "SDN": 43.8,
    "TZA": 59.7, "TGO": 8.3, "TUN": 11.8, "UGA": 47.0, "ZMB": 18.4, "ZWE": 14.9,
    "ESH": 0.58,
}

# Island states (off the Albers mainland): ISO3 -> local UTM EPSG
ISLAND_CRS = {
    "CPV": "EPSG:32626",  # 26N
    "STP": "EPSG:32632",  # 32N
    "SYC": "EPSG:32740",  # 40S
    "MUS": "EPSG:32740",  # 40S
    "COM": "EPSG:32738",  # 38S
}

MAINLAND_CRS = "ESRI:102022"  # Africa Albers Equal Area Conic

TEMPLATE = """# Country profile: {name}
# Generated by tools/gen_profiles.py from the {date} source audit.

iso3: {iso3}
name: "{name}"
profile_version: 0.3.0
hdx_slug: {slug}
crs_analysis: "{crs}"

layers:
  admin_boundaries:
    adapter: codab
    params:
      admin_levels: [0, 1, 2]

  population:
    adapter: worldpop
    params:
      year: 2020
      dataset: ppp

  # Optional: skipped with a warning if this country has no healthsites dataset.
  facilities:
    adapter: healthsites
    optional: true

checks:
  # UN WPP 2020 estimate: {pop:.2f}M; gate is +/-40% (min 0.10M wide).
  expected_population_total_millions: [{lo:.2f}, {hi:.2f}]

viewer:
  choropleth_field: population_sum
  choropleth_label: "Population (WorldPop 2020, unconstrained)"
"""


def main() -> None:
    audit = json.loads((ROOT / "tools" / "africa_audit.json").read_text(encoding="utf-8"))
    written, skipped = [], []
    for row in audit:
        iso3 = row["iso3"]
        if not (row["codab"] and row["worldpop"]):
            skipped.append(f"{iso3} (missing sources)")
            continue
        path = ROOT / "profiles" / f"{iso3}.yaml"
        if path.exists():
            skipped.append(f"{iso3} (profile exists)")
            continue
        pop = POP_2020_M[iso3]
        width = max(pop * 0.40, 0.10)
        path.write_text(TEMPLATE.format(
            name=row["name"], iso3=iso3, slug=f"cod-ab-{iso3.lower()}",
            crs=ISLAND_CRS.get(iso3, MAINLAND_CRS),
            date="2026-10-25", pop=pop, lo=pop - width, hi=pop + width,
        ), encoding="utf-8")
        written.append(iso3)
    print(f"written: {len(written)} profiles")
    for iso in written:
        print(f"  + {iso}")
    print(f"skipped: {len(skipped)}")
    for s in skipped:
        print(f"  - {s}")


if __name__ == "__main__":
    main()
